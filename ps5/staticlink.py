#!/usr/bin/env python3
"""Turn the engine's shared modules into one statically linkable archive.

For every module (shared library in the waf build) we:
  1. partially link its objects and engine-internal static archives (ld -r),
  2. drop COMDAT groups so the final link cannot discard another module's copy,
  3. rename dl* references to the ps5_dl* shim and exports to <module>__<sym>,
  4. localize every other defined symbol (so each module keeps private copies
     of tier1/mathlib/... exactly like separate .so files would).
"Global" libraries (tier0, vstdlib, togl, steam_api) are linked normally by
other modules, so the symbols other modules import from them stay global.

Input: a JSON file {module: {"objects": [...], "archives": [...],
                              "shared": [module, ...]}} produced by
ps5/collect-links.py.  Output: <out>/modules/*.o, <out>/ps5_static_table.c.
"""
import argparse, json, os, re, subprocess, sys
from pathlib import Path

GLOBAL_LIBS = {"tier0", "vstdlib", "togl", "steam_api"}
EXPORTS = ["CreateInterface", "LauncherMain"]
DL_FUNCS = ["dlopen", "dlsym", "dlclose", "dlerror"]
SDK_BIN = Path(os.environ["PS5_PAYLOAD_SDK"]) / "bin"
LLD = str(SDK_BIN / "ld.lld")
OBJCOPY = str(SDK_BIN / "llvm-objcopy")
NM = str(SDK_BIN / "llvm-nm")


def run(*args):
    r = subprocess.run([str(a) for a in args], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"command failed: {' '.join(map(str, args))}\n{r.stderr}")
    return r.stdout


def symbols(obj):
    defined, undefined = set(), set()
    for line in run(NM, "--extern-only", "--format=just-symbols", "--defined-only", obj).split():
        defined.add(line)
    for line in run(NM, "--extern-only", "--format=just-symbols", "--undefined-only", obj).split():
        undefined.add(line)
    return defined, undefined


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("links", help="module link description JSON")
    ap.add_argument("out")
    args = ap.parse_args()
    links = json.loads(Path(args.links).read_text())
    out = Path(args.out)
    (out / "partial").mkdir(parents=True, exist_ok=True)
    (out / "modules").mkdir(parents=True, exist_ok=True)

    partial, syms = {}, {}
    for mod, spec in sorted(links.items()):
        p = out / "partial" / f"{mod}.o"
        run(LLD, "-r", "-o", p, *spec["objects"], "--start-group", *spec["archives"], "--end-group")
        partial[mod] = p
        syms[mod] = symbols(p)
        print(f"partial  {mod:24s} defined={len(syms[mod][0])} undefined={len(syms[mod][1])}")

    # What each global library must keep visible: symbols others import from it.
    imported = set()
    for mod, (_, undef) in syms.items():
        imported |= undef
    table = []
    for mod, p in sorted(partial.items()):
        defined, _ = syms[mod]
        keep = []
        cmd = [OBJCOPY]
        for name in EXPORTS:
            if name in defined:
                new = f"{mod}__{name}"
                cmd += ["--redefine-sym", f"{name}={new}"]
                keep.append(name)
                table.append((mod, name, new))
        for name in DL_FUNCS:
            cmd += ["--redefine-sym", f"{name}=ps5_{name}"]
        if mod in GLOBAL_LIBS:
            keep += sorted((defined & imported) - set(EXPORTS))
        keep_file = out / "partial" / f"{mod}.keep"
        keep_file.write_text("".join(k + "\n" for k in keep))
        final = out / "modules" / f"{mod}.o"
        cmd += ["--remove-section=.group", f"--keep-global-symbols={keep_file}", p, final]
        run(*cmd)
        print(f"module   {mod:24s} kept-global={len(keep)}")

    lines = ["/* generated by ps5/staticlink.py */",
             "typedef struct { const char *module, *name; void *addr; } PS5StaticSymbol;"]
    for _, _, sym in table:
        lines.append(f"extern char {sym}[];")
    lines.append("const PS5StaticSymbol g_ps5_static_symbols[] = {")
    for mod, name, sym in table:
        lines.append(f'  {{"{mod}", "{name}", {sym}}},')
    lines.append("  {0, 0, 0}\n};")
    (out / "ps5_static_table.c").write_text("\n".join(lines) + "\n")
    print(f"table: {len(table)} exports")


if __name__ == "__main__":
    main()
